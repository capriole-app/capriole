#!/usr/bin/env python3
"""Generates engine/src/content/cmyk_table.cpp: DeviceCMYK → sRGB sampled from the SWOP2006_Coated3v2
press profile (ADR 0006) on a 9 × 9 × 9 × 9 grid, for the engine to interpolate when the host has not
supplied the profile itself (the resource pack). Relative colorimetric intent with black point
compensation, as Acrobat displays CMYK.

    scripts/gen_cmyk_table.py [SWOP2006_Coated3v2.icc]   # else downloaded from the ICC profile registry

The profile is IDEAlliance's ("may be used, embedded, exchanged, and shared without restriction"); only
the colours it gives at the grid points are written here. Needs Pillow (its ImageCms is Little CMS).
"""

import hashlib
import io
import sys
import urllib.request
from pathlib import Path

from PIL import Image, ImageCms

URL = "https://registry.color.org/profile-registry/profiles/SWOP2006_Coated3v2.icc"
SHA256 = "27dc90dbeb399b76c0f91a6b387fe30c38939f034d2500712f3c43094be15e3b"
OUT = Path(__file__).resolve().parent.parent / "engine/src/content/cmyk_table.cpp"
N = 9  # grid points per ink


def main():
    if len(sys.argv) > 1:
        data = Path(sys.argv[1]).read_bytes()
    else:
        with urllib.request.urlopen(URL) as response:
            data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"profile SHA-256 {digest}, expected {SHA256}")
    swop = ImageCms.ImageCmsProfile(io.BytesIO(data))
    srgb = ImageCms.createProfile("sRGB")
    transform = ImageCms.buildTransform(swop, srgb, "CMYK", "RGB", renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC,
                                        flags=ImageCms.FLAGS["BLACKPOINTCOMPENSATION"])
    # Grid order: c slowest, then m, y, k fastest.
    levels = [round(i * 255 / (N - 1)) for i in range(N)]
    pixels = [(c, m, y, k) for c in levels for m in levels for y in levels for k in levels]
    image = Image.new("CMYK", (len(pixels), 1))
    image.putdata(pixels)
    rgb = ImageCms.applyTransform(image, transform)
    values = [channel for pixel in rgb.getdata() for channel in pixel]
    rows = [", ".join(str(v) for v in values[i:i + 36]) for i in range(0, len(values), 36)]
    OUT.write_text(
        "// Generated by scripts/gen_cmyk_table.py — do not edit. DeviceCMYK → sRGB sampled from the\n"
        f"// SWOP2006_Coated3v2 profile (IDEAlliance, SHA-256 {SHA256[:16]}…) on a {N}^4 grid:\n"
        "// relative colorimetric, black point compensation. c slowest, k fastest; 3 bytes per point.\n"
        "// clang-format off\n"
        '#include "cmyk_table.hpp"\n\n'
        "namespace capriole::content::detail {\n\n"
        f"const std::array<std::uint8_t, {len(values)}> kCmykTable = {{{{\n    " + ",\n    ".join(rows) + "\n}};\n\n"
        "}  // namespace capriole::content::detail\n")
    print(f"{OUT}: {len(pixels)} grid points")


if __name__ == "__main__":
    main()
